/* ── FOOTER RENDERER ── */
export function renderFooter(footer: FooterData): string {
    
  const columnsHtml = footer.columns
    .map((col: FooterColumn) => {
      const linksHtml = col.links
        .map((link: FooterLink) => `
          <li>
            <a href="${link.href}">${link.text}</a>
          </li>
        `).join('');

      return `
        <div>
          <h4 class="footer-heading">${col.title}</h4>
          <ul class="footer-links">
            ${linksHtml}
          </ul>
          
        </div>
      `;
    }).join('');

  const socialHtml = footer.social
    .map((item: FooterSocial) => {
        const iconSvg = SOCIAL_ICONS[item.id] || `<span class="icon-text">${item.id.toUpperCase()}</span>`;
        return `
      <a href="${item.href}" 
         class="social-icon social-icon--${item.id}" 
         target="_blank" 
         rel="noopener noreferrer" 
         aria-label="${item.label}">
         ${iconSvg}
      </a>
    `}).join('');

  const waFloatHtml = renderWAFloat(footer);
  return `
    <footer>
      <div class="footer-grid">
        <div>
          <div class="footer-brand-name">${footer.name}</div>
          <div class="footer-brand-sub">${footer.specialty}</div>
          <p class="footer-desc">${footer.description}</p>
        </div>
        <div id="footer-columnas" style="display:contents;">
          ${columnsHtml}
        </div>
      </div>
      <div class="footer-bottom">
        <p class="footer-copy">${footer.copyright}</p>
        <div class="social-bar" id="footer-social">
          ${socialHtml}
        </div>
      </div>
    </footer>
    ${waFloatHtml}
  `;
}